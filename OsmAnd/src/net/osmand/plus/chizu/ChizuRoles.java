package net.osmand.plus.chizu;

import android.content.Context;
import android.content.SharedPreferences;
import android.util.SparseIntArray;

import androidx.annotation.ColorInt;
import androidx.annotation.NonNull;
import androidx.core.graphics.ColorUtils;

import java.util.ArrayList;
import java.util.List;

/**
 * 白い熊 地図 5.6.0+004: the item colour roles (black-yellow skill, “Colours”, the MIXED way — 白い熊,
 * 2026-11-24). OsmAnd's layouts, themes and code keep naming OsmAnd's own colours; every such colour that
 * is an item of the UI has a role here, set on the UI page in the section of its item. A role feeds the
 * dark and the light name alike, so 地図 is black and yellow whichever theme is on.
 * <p>
 * A role that was never set follows its rule: the two primaries reach it through the foundation colours
 * of the page ({@link ChizuTheme.Slot}), so changing the accent moves every accent-ruled item with it.
 * The table itself is {@link ChizuRoleTable}, generated by {@code tools/chizu/gen_roles.py}.
 * <p>
 * The values reach the app two ways: {@link ChizuTheme#overrideFor(int)} for colours taken through
 * {@code ColorUtilities}, and {@link ChizuPalette} for everything XML and the rest of the code read.
 */
public final class ChizuRoles {

	/** How a role's default is derived. */
	enum Rule {
		GROUND, TEXT, DIM, ACCENT, ICON, LINE,
		/** Content drawn on an accent fill: black or white, whichever reads. */
		ON_ACCENT,
		/** {@code f} of the way from the ground to the accent, opaque. */
		MIX,
		ACCENT_ALPHA, GROUND_ALPHA, TEXT_ALPHA,
		/** A colour that carries meaning: upstream's own value. */
		KEEP
	}

	/** One item's colour. */
	public static final class Role {
		public final String key;
		public final String section;
		public final int labelRes;
		final Rule rule;
		final float f;
		final int literal;
		final int[] res;

		Role(String key, String section, int labelRes, Rule rule, float f, int literal, int[] res) {
			this.key = key;
			this.section = section;
			this.labelRes = labelRes;
			this.rule = rule;
			this.f = f;
			this.literal = literal;
			this.res = res;
		}

		String prefKey() {
			return "chizu_role_" + key;
		}
	}

	private ChizuRoles() {
	}

	@NonNull
	public static List<Role> inSection(@NonNull String section) {
		List<Role> out = new ArrayList<>();
		for (Role r : ChizuRoleTable.ALL) {
			if (r.section.equals(section)) {
				out.add(r);
			}
		}
		return out;
	}

	private static int alpha(@ColorInt int color, float f) {
		return (color & 0x00FFFFFF) | (Math.max(0, Math.min(255, Math.round(f * 255f))) << 24);
	}

	@ColorInt
	private static int defaultColor(@NonNull SharedPreferences prefs, @NonNull Role r) {
		int ground = ChizuTheme.slotColor(prefs, ChizuTheme.Slot.BACKGROUND);
		int accent = ChizuTheme.slotColor(prefs, ChizuTheme.Slot.ACCENT);
		int text = ChizuTheme.slotColor(prefs, ChizuTheme.Slot.TEXT);
		switch (r.rule) {
			case GROUND:
				return ground;
			case TEXT:
				return text;
			case DIM:
				return ChizuTheme.slotColor(prefs, ChizuTheme.Slot.TEXT_SECONDARY);
			case ACCENT:
				return accent;
			case ICON:
				return ChizuTheme.slotColor(prefs, ChizuTheme.Slot.ICON);
			case LINE:
				return ChizuTheme.slotColor(prefs, ChizuTheme.Slot.DIVIDER);
			case ON_ACCENT:
				return ChizuTheme.contrastOn(accent);
			case MIX:
				return ColorUtils.blendARGB(ground | 0xFF000000, accent | 0xFF000000, r.f);
			case ACCENT_ALPHA:
				return alpha(accent, r.f);
			case GROUND_ALPHA:
				return alpha(ground, r.f);
			case TEXT_ALPHA:
				return alpha(text, r.f);
			case KEEP:
			default:
				return r.literal;
		}
	}

	@ColorInt
	static int color(@NonNull SharedPreferences prefs, @NonNull Role r) {
		int stored = prefs.getInt(r.prefKey(), ChizuTheme.UNSET);
		return stored != ChizuTheme.UNSET ? stored : defaultColor(prefs, r);
	}

	@ColorInt
	public static int color(@NonNull Context c, @NonNull Role r) {
		return color(ChizuTheme.prefs(c), r);
	}

	public static boolean isSet(@NonNull Context c, @NonNull Role r) {
		return ChizuTheme.prefs(c).getInt(r.prefKey(), ChizuTheme.UNSET) != ChizuTheme.UNSET;
	}

	public static void set(@NonNull Context c, @NonNull Role r, @ColorInt int color) {
		ChizuTheme.prefs(c).edit().putInt(r.prefKey(), color).apply();
		ChizuTheme.rebuildOverrides();
	}

	/** Back to the role's rule. */
	public static void reset(@NonNull Context c, @NonNull Role r) {
		ChizuTheme.prefs(c).edit().remove(r.prefKey()).apply();
		ChizuTheme.rebuildOverrides();
	}

	static void clearAll(@NonNull SharedPreferences.Editor editor) {
		for (Role r : ChizuRoleTable.ALL) {
			editor.remove(r.prefKey());
		}
	}

	/** Every role's colour, by each colour resource it feeds. */
	static void fill(@NonNull SharedPreferences prefs, @NonNull SparseIntArray out) {
		for (Role r : ChizuRoleTable.ALL) {
			int color = color(prefs, r);
			for (int id : r.res) {
				out.put(id, color);
			}
		}
	}
}
